/**
 * Проверка цифрового следа — содержательная часть.
 *
 * Инструмент проверяет не «что о вас в интернете» (снаружи это узнать нельзя
 * и лезть в чужую выдачу мы не станем), а цепочку из пяти звеньев, разобранную
 * в статье «Прецедент»: событие произошло → его зафиксировали с вашим именем →
 * кто-то это увидел → набрал имя в поиске → нашёл вашу страницу.
 *
 * Смысл в том, чтобы человек увидел, на каком именно звене у него обрыв.
 * Четыре звена из пяти чинятся вниманием и одним письмом организатору, и
 * говорить об этом надо прямо: инструмент, который любой ответ сводит к
 * «закажите биографию», перестаёт быть проверкой и становится рекламой.
 */

export interface Answer {
  value: string
  label: string
  /** Балл звена: 2 — держит, 1 — держит наполовину, 0 — рвётся. */
  score: 0 | 1 | 2
}

export interface Question {
  /** Ключ в адресе страницы: `?sobytie=da`. Короткий, чтобы ссылка читалась. */
  key: string
  /** Номер звена цепочки, к которому относится вопрос. */
  link: number
  question: string
  /** Зачем этот вопрос — одна строка под ним, без неё вопрос выглядит анкетой. */
  hint: string
  answers: Answer[]
}

