export interface LinkVerdict {
  link: number
  title: string
  state: 'ok' | 'weak' | 'broken'
  /** Что это значит — без совета. */
  meaning: string
  /** Что делать. Пусто, если делать нечего. */
  action?: string
}

const TITLES: Record<number, string> = {
  1: 'Событие произошло',
  2: 'Его зафиксировали с вашим именем',
  4: 'Кто-то набрал имя в поиске',
  5: 'И нашёл вашу страницу',
}

/**
 * Разбор ответов по звеньям. Звено 3 — «кто-то это увидел» — в проверке не
 * участвует: оно зависит от площадки, а не от человека, и спрашивать о нём
 * означало бы требовать от читателя данных, которых у него нет.
 */
export function verdict(answers: Record<string, string>): LinkVerdict[] {
  const score = (key: string): number | undefined => {
    const q = QUESTIONS.find((x) => x.key === key)
    return q?.answers.find((a) => a.value === answers[key])?.score
  }

  const out: LinkVerdict[] = []

  const sobytie = score('sobytie')
  if (sobytie !== undefined) {
    out.push({
      link: 1,
      title: TITLES[1],
      state: sobytie === 2 ? 'ok' : sobytie === 1 ? 'weak' : 'broken',
      meaning:
        sobytie === 2
          ? 'Поводы есть. Это половина работы, и она уже сделана.'
          : sobytie === 1
            ? 'Поводы есть, но их мало. Один прецедент даёт всплеск на несколько дней и затухает; работает последовательность.'
            : 'Прецедентов нет — значит, имени неоткуда взяться в чужом тексте, и остальные звенья проверять не на чем.',
      action:
        sobytie === 2
          ? undefined
          : 'Наметьте один повод на ближайший квартал — самый дешёвый из доступных: доклад на профильном мероприятии или комментарий изданию по вашей теме.',
    })
  }

  const imya = score('imya')
  const forma = score('forma')
  if (imya !== undefined || forma !== undefined) {
    const worst = Math.min(imya ?? 2, forma ?? 2)
    const problems: string[] = []
    if (imya !== undefined && imya < 2) problems.push('имя названо не везде')
    if (forma !== undefined && forma === 0) problems.push('форма имени плавает')
    if (forma !== undefined && forma === 1) problems.push('форма имени не проверена')
    out.push({
      link: 2,
      title: TITLES[2],
      state: worst === 2 ? 'ok' : worst === 1 ? 'weak' : 'broken',
      meaning:
        worst === 2
          ? 'Имя стоит в текстах целиком и в одной форме — по нему можно искать.'
          : `Здесь обрыв: ${problems.join(', ')}. Событие было, а повода не возникло: искать нечего или ищут не то.`,
      action:
        worst === 2
          ? undefined
          : 'Оба разрыва чинятся вниманием, а не деньгами. При согласовании любого упоминания просите указать имя, фамилию и должность — это нормальная просьба, её выполняют. И заведите одну каноническую форму имени: в подписи, в договорах, в профилях.',
    })
  }

  const odno = score('odnofamilcy')
  if (odno !== undefined) {
    out.push({
      link: 4,
      title: TITLES[4],
      state: odno === 2 ? 'ok' : odno === 1 ? 'weak' : 'broken',
      meaning:
        odno === 2
          ? 'Фамилия работает на вас: запрос по ней приведёт к вам.'
          : odno === 1
            ? 'Стоит проверить: если однофамилец известнее, часть запросов уйдёт к нему.'
            : 'Запрос по одной фамилии уходит к однофамильцу. Это не чинится ничем, кроме связки имени с темой.',
      action:
        odno === 2
          ? undefined
          : 'Сформулируйте связку из трёх слов: фамилия плюс тема. По ней вас должны находить через год — и дальше отбирайте поводы только те, что в неё укладываются.',
    })
  }

  const stranica = score('stranica')
  if (stranica !== undefined) {
    out.push({
      link: 5,
      title: TITLES[5],
      state: stranica === 2 ? 'ok' : stranica === 1 ? 'weak' : 'broken',
      meaning:
        stranica === 2
          ? 'Место приземления есть: человек, услышавший ваше имя, находит факты.'
          : stranica === 1
            ? 'Соцсеть — слабое место приземления: она показывает, чем вы заняты, но не отвечает на вопрос, кто вы и что сделали.'
            : 'Это не нейтральный исход, а отрицательный: пустая выдача подтверждает подозрение, что за именем ничего нет.',
      action:
        stranica === 2
          ? undefined
          : 'Нужна страница, где рядом с именем стоят специальность, организация, годы и ссылки на источники.',
    })
  }

  return out
}

