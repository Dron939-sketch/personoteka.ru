import type { Person } from './types'

/**
 * Текст обязательной маркировки материала о лице, включённом в реестр
 * иностранных агентов (255-ФЗ).
 *
 * Живёт в `lib`, а не в компоненте: пометку несёт не только страница, но и
 * PDF-досье, а его вёрстка на React PDF не должна тянуть за собой CSS-модули.
 * Расходиться эти два текста не имеют права — формулировка одна на оба места.
 *
 * Утверждённая форма называет иностранного агента поимённо, поэтому имя
 * подставляется, а не опускается: обезличенная пометка форме не соответствует.
 * Остальной текст не сокращается и не пересказывается.
 */
export function foreignAgentNoticeText(person: Person): string | undefined {
  if (!person.foreign_agent?.listed) return undefined

  const name = (person.foreign_agent.registry_name ?? person.full_name).toUpperCase()

  return (
    `НАСТОЯЩИЙ МАТЕРИАЛ (ИНФОРМАЦИЯ) ПРОИЗВЕДЁН, РАСПРОСТРАНЁН И (ИЛИ) НАПРАВЛЕН ` +
    `ИНОСТРАННЫМ АГЕНТОМ ${name}, ЛИБО КАСАЕТСЯ ДЕЯТЕЛЬНОСТИ ИНОСТРАННОГО АГЕНТА ${name}.`
  )
}
