import fs from 'node:fs'
import path from 'node:path'

import type { NextConfig } from 'next'

/**
 * Страницы персон статические (SSG) с ревалидацией по вебхуку из CMS — см. §9.1 ТЗ.
 * Пока источник контента — файлы в `content/`, ревалидация не нужна;
 * при переезде на headless CMS достаточно заменить слой `src/lib/content.ts`.
 */
const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  // Все адреса из §4.1 записаны со слешом на конце (`/imya-familiya/`, `/katalog/`).
  // Без этого флага Next редиректит их на вариант без слеша, и канонический адрес
  // в разметке расходится с тем, что реально отдаёт сервер.
  trailingSlash: true,
  images: {
    // Только WebP, без AVIF — осознанный размен, подтверждённый замером.
    //
    // Оптимизатор Next кодирует кадр при первом запросе, одним процессом,
    // а кэш готовых кадров лежит внутри контейнера и стирается при каждой
    // пересборке. То есть за кодирование платит живой человек, открывший
    // каталог первым после выкладки, — и платит заново после каждой.
    //
    // Одна и та же страница каталога на холодном кэше, 33 портрета:
    //
    //             медиана   90-й перцентиль   максимум   суммарный вес
    //   AVIF       386 мс        600 мс        677 мс        564 КБ
    //   WebP       108 мс        227 мс        250 мс        842 КБ
    //
    // AVIF на треть легче, но втрое медленнее. Лишние восемь килобайт
    // на портрет — это около десятка миллисекунд на мобильной сети и один
    // раз на год вперёд (кэш ниже); триста миллисекунд ожидания платятся
    // каждым первым посетителем и видны глазом.
    formats: ['image/webp'],
    // §7.5: srcset на 4 ширины для портретов 4:5
    imageSizes: [240, 320, 480, 640],
    deviceSizes: [640, 768, 1024, 1280, 1440],
    // Год вместо четырёх часов по умолчанию. Адрес портрета содержит версию
    // файла (`/media/v<хеш>/<слаг>.jpg`, см. `rewrites`), поэтому замена
    // фотографии меняет и адрес — «навсегда» здесь безопасно. Без версии
    // этого делать было нельзя: заменённый портрет висел бы в кэше год.
    minimumCacheTTL: 31_536_000,
  },
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          {
            key: 'Strict-Transport-Security',
            value: 'max-age=63072000; includeSubDomains; preload',
          },
        ],
      },
    ]
  },
  async rewrites() {
    // Версионированный адрес портрета: `/media/v1a2b3c4d/alsu.jpg` отдаёт
    // тот же файл, что и `/media/alsu.jpg`.
    //
    // Версия нужна, чтобы держать кэш готовых кадров год (см. `images`),
    // и при этом иметь возможность заменить портрет: адрес меняется вместе
    // с содержимым файла. Сегментом пути, а не строкой запроса: Next 16
    // требует объявлять допустимые query для локальных картинок точным
    // совпадением, а хеш у каждого портрета свой. Копий файлов при этом
    // не появляется — на диске по-прежнему один `<слаг>.jpg`.
    return [
      {
        source: '/media/v:version([0-9a-f]{8})/:name',
        destination: '/media/:name',
      },
    ]
  },
  async redirects() {
    // 301 для изменённых слагов персон (§4.1: старый слаг остаётся навсегда и не отдаёт 404).
    // Реестр читается из файла, а не импортируется: конфиг Next компилируется отдельным
    // файлом, и относительный импорт из него не резолвится.
    const file = path.join(process.cwd(), 'content/redirects.json')
    const registry = JSON.parse(fs.readFileSync(file, 'utf8')) as { from: string; to: string }[]
    // Слеши на обоих концах: иначе к 301 добавляется ещё пара нормализующих
    // редиректов, и старый адрес приходит к новому цепочкой из трёх переходов.
    return registry.map((r) => ({
      source: `/${r.from}/`,
      destination: `/${r.to}/`,
      permanent: true,
    }))
  },
}

export default nextConfig
